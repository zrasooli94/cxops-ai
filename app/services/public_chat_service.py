def hash_digest(value: str) -> str:
    """Deterministic SHA-256 hex digest used for all stored secrets."""
    return hashlib.sha256(value.encode("utf-8")).hexdigest()


def _truncate(value: str, max_length: int) -> str:
    if len(value) <= max_length:
        return value
    return value[: max_length - 3] + "..."


# Internal citation markers (``[S1]``) point at stored knowledge chunks and are
# meaningless to a customer. They are stripped before any grounded answer is
# published; the answer is only eligible when its citations are valid, so the
# removal never hides an untraceable claim.
_SOURCE_MARKER_PATTERN = re.compile(r"\s*\[S\d+\]")
_WHITESPACE_RUN_PATTERN = re.compile(r"[ \t]{2,}")


def _strip_source_markers(answer: str) -> str:
    """Remove internal ``[S<n>]`` citation markers from a public answer.

    Removing an inline marker can leave a doubled space or a space before
    punctuation. The whitespace collapse keeps the published sentence readable;
    it only touches runs of spaces/tabs and never changes a real character.
    """
    stripped = _SOURCE_MARKER_PATTERN.sub("", answer)
    return _WHITESPACE_RUN_PATTERN.sub(" ", stripped).strip()


@dataclass(frozen=True)
class _GroundedAutoReply:
    """A validated, customer-safe answer plus the evidence behind it.

    The text is the only customer-visible field; the rest is carried so the
    caller can emit an operational log and a run event without re-querying RAG.
    """

    text: str
    request_id: str | None
    retrieval_count: int
    best_similarity: float | None
    source_ids: tuple[str, ...]


