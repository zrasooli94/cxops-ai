    @classmethod
    async def _mirror_first_message_to_ticket(
        cls,
        db: AsyncSession,
        *,
        ticket: Ticket,
        text: str,
    ) -> None:
        """Refine the placeholder ticket from the first customer message."""
        organization_id = ticket.organization_id
        if organization_id is None:
            raise ValueError("Ticket must be tenant-owned")
        if ticket.subject != TICKET_PLACEHOLDER_SUBJECT:
            return
        await TicketRepository.update_for_tenant(
            db,
            ticket=ticket,
            changes={
                "subject": _truncate(text, 255),
                "description": text,
            },
            organization_id=organization_id,
        )
        await ConversationIngestionService.sync_ticket_conversation(
            db,
            ticket=ticket,
            organization_id=organization_id,
        )

    @staticmethod
    def _grounded_auto_reply_requested(
        *,
        configuration: PublicChatConfiguration,
        result: dict,
        run: AgentRun | None,
    ) -> bool:
        """Whether this turn may use the tenant's grounded auto-reply opt-in.

        The carve-out is deliberately narrow: the tenant must have enabled it,
        the coordinator must have classified the request as purely
        ``information``, and the agent decision must be a bare ``respond`` with
        no business tool. Anything else stays handoff-only.
        """
        if not configuration.grounded_auto_reply_enabled:
            return False
        if run is None or run.action != "respond":
            return False
        if result.get("coordinator_intent") != "information":
            return False
        decision = result.get("decision") or {}
        return not decision.get("business_tool")

    @classmethod
    async def _grounded_auto_reply_or_none(
        cls,
        db: AsyncSession,
        *,
        organization_id: int,
        question: str,
    ) -> _GroundedAutoReply | None:
        """Produce a bounded public answer, or ``None`` when not eligible.

        Runs a fresh tenant-scoped RAG answer and returns it only when it is
        grounded with valid citations. A retrieval error propagates so the
        caller can roll the transaction back before falling back to handoff;
        an ineligible answer simply returns ``None``. The citation markers are
        validated on the raw answer, then removed for the customer.
        """
        rag_result = await rag_service.answer(
            db,
            organization_id=organization_id,
            question=question,
            feature="public_chat",
        )

        eligible, reason = public_answer_eligible(rag_result)
        if not eligible:
            log.info("public_chat_grounded_auto_reply_ineligible", reason=reason)
            return None

        answer = _strip_source_markers(rag_result.get("answer") or "")
        if not answer:
            return None

        sources = rag_result.get("sources") or []
        source_ids = tuple(
            str(source["source_id"])
            for source in sources
            if source.get("source_id")
        )
        return _GroundedAutoReply(
            text=answer,
            request_id=rag_result.get("request_id"),
            retrieval_count=int(rag_result.get("retrieval_count") or 0),
            best_similarity=rag_result.get("best_similarity"),
            source_ids=source_ids,
        )

    @staticmethod
    async def _record_rag_failure(
        db: AsyncSession,
        *,
        organization_id: int,
    ) -> None:
        """Persist a durable, bounded observability row for a failed RAG attempt.

        The RAG failure path in ``send_message`` rolls the attempt's transaction
        back before failing closed to handoff (so a retrieval/model error can
        never surface as a 500). This marker re-records the failed attempt with
        ``feature='public_chat'`` and ``status='error'`` so the pilot summary
        can count real RAG failures instead of always reporting zero. It stores
        a bounded placeholder — never the customer's raw question text — and no
        model output, error trace, or customer identity is retained. The row is
        committed with the handoff reply that follows.
        """
        db.add(
            AIRequestLog(
                organization_id=organization_id,
                request_id=uuid4().hex,
                feature="public_chat",
                model=settings.chat_model,
                status="error",
                question=RAG_FAILURE_PLACEHOLDER_QUESTION,
                answer=None,
                grounded=False,
                llm_called=False,
                retrieval_count=0,
                best_similarity=None,
                sources=[],
                latency_ms=0.0,
                error_message="public_chat_grounded_auto_reply_failed",
            )
        )

    @staticmethod
    async def _record_grounded_auto_reply(
        db: AsyncSession,
        *,
        run: AgentRun,
        session: PublicChatSession,
        reply: _GroundedAutoReply,
    ) -> None:
        """Record that a grounded auto-reply was published.

        The audit trail is deliberately metadata-only: source ids and scores,
        never the customer question or the answer text. It is emitted only
        after the outbound message is persisted, so the run event cannot claim
        a reply the customer never received.
        """
        log.info(
            "public_chat_grounded_auto_reply_sent",
            organization_id=session.organization_id,
            session_id=session.id,
            run_id=run.id,
            retrieval_count=reply.retrieval_count,
            best_similarity=reply.best_similarity,
        )
        await AgentRunRepository.add_event(
            db,
            agent_run_id=run.id,
            event_type="public_grounded_auto_reply",
            actor="public_chat",
            event_data={
                "rag_request_id": reply.request_id,
                "retrieval_count": reply.retrieval_count,
                "best_similarity": reply.best_similarity,
                "source_ids": list(reply.source_ids),
                "eligibility_reason": "eligible",
            },
        )

    @classmethod
    async def send_message(
        cls,
        db: AsyncSession,
        *,
        session_token: str,
        embedding_origin: str | None,
        text: str,
        client_message_id: str,
        delivery: str = "sync",
    ) -> dict:
        """Append an inbound message and run (or enqueue) the agent turn.

        Idempotent by ``client_message_id``: a retry resolves the already
        persisted inbound + reply messages and returns them, and the reply is
        keyed by the same id so the returned text is stable.

        ``delivery="sync"`` (default, the original contract) runs the AI turn
        inside this request. ``delivery="async"`` (Phase 1P.9) persists the
        message, enqueues a durable tenant-bound turn job, and returns
        ``processing_state="accepted"`` immediately; the reply arrives through
        ``get_updates``.
        """
        timer = _StageTimer()
        session = await cls.verify_session(db, session_token)
        configuration = await PublicChatRepository.get_config_by_id_for_tenant(
            db,
            configuration_id=session.configuration_id,
            organization_id=session.organization_id,
        )
        if configuration is None:
            raise PublicChatConfigurationNotFoundError(
                "The widget configuration was not found."
            )
        cls.validate_embedding_origin(configuration, embedding_origin)

        if len(text) > configuration.max_message_length:
            raise PublicChatInputTooLongError(
                f"Messages are limited to {configuration.max_message_length} characters."
            )

        await cls._maybe_prune_rate_buckets(db)
        if not await public_chat_rate_limiter_db.allow(
            db,
            scope="session_messages",
            key=f"session:{session.id}",
            limit=configuration.max_messages_per_minute,
            window_seconds=60.0,
        ):
            raise PublicChatRateLimitedError(
                "You are sending messages too quickly. Please wait a moment."
            )
        if not await public_chat_rate_limiter_db.allow(
            db,
            scope="config_messages",
            key=f"config:{configuration.id}",
            limit=settings.public_chat_max_messages_per_minute_per_config,
            window_seconds=60.0,
        ):
            raise PublicChatRateLimitedError(
                "The widget is busy. Please try again in a moment."
            )

        conversation_result = await db.execute(
            select(Conversation).where(
                Conversation.id == session.conversation_id,
                Conversation.organization_id == session.organization_id,
            )
        )
        conversation = conversation_result.scalar_one_or_none()
        if conversation is None:
            raise PublicChatSessionNotFoundError("Session conversation not found.")

        timer.mark("validate")
        use_async = delivery == "async" and settings.public_chat_async_enabled

        # ---- early duplicate: retry returns the already-persisted reply ----
        inbound = await ConversationMessageRepository.get_by_dedupe_key(
            db,
            conversation_id=conversation.id,
            organization_id=conversation.organization_id,
            dedupe_key=f"{DEDUPE_INBOUND_PREFIX}{client_message_id}",
        )
        if inbound is not None:
            reply = await ConversationMessageRepository.get_by_dedupe_key(
                db,
                conversation_id=conversation.id,
                organization_id=conversation.organization_id,
                dedupe_key=f"{DEDUPE_REPLY_PREFIX}{client_message_id}",
            )
            if reply is not None:
                handoff_text = await cls.handoff_reply_for(
                    db, session.organization_id
                )
                handoff = reply.body == handoff_text
                return {
                    "message_id": inbound.id,
                    "reply": reply.body,
                    "status": session.status,
                    "handoff": handoff,
                    "processing_state": "handoff" if handoff else "completed",
                }
            if session.status in HANDED_OFF_STATUSES:
                # A handed-off message never creates an outbound reply, so the
                # persisted inbound row alone satisfies idempotency. Returning
                # reply=None here (instead of raising in-flight) keeps a retry
                # stable for the lifetime of the session.
                return {
                    "message_id": inbound.id,
                    "reply": None,
                    "status": session.status,
                    "handoff": session.status == "human_requested",
                    "processing_state": "handoff",
                }
            if use_async:
                # The message was accepted before; make sure its turn exists
                # (idempotent) - this also repairs a crash between persisting
                # the message and enqueueing its turn.
                job_id = await cls._ensure_turn_job(
                    db,
                    session=session,
                    inbound_id=inbound.id,
                    client_message_id=client_message_id,
                )
                return cls._accepted(session=session, inbound_id=inbound.id, job_id=job_id)
            raise PublicChatMessageInFlightError(
                "This message is still being processed."
            )

        inbound = await cls._insert_inbound_message(
            db,
            conversation=conversation,
            text=text,
            client_message_id=client_message_id,
        )

        ticket_result = await db.execute(
            select(Ticket).where(
                Ticket.id == session.ticket_id,
                Ticket.organization_id == session.organization_id,
            )
        )
        ticket = ticket_result.scalar_one_or_none()
        if ticket is None:
            raise PublicChatSessionNotFoundError("Session ticket not found.")

        if ticket.subject == TICKET_PLACEHOLDER_SUBJECT:
            await cls._mirror_first_message_to_ticket(
                db,
                ticket=ticket,
                text=text,
            )
        else:
            await ConversationRepository.update_for_tenant(
                db,
                conversation=conversation,
                changes={"latest_message_at": datetime.now(UTC)},
                organization_id=conversation.organization_id,
            )

        if session.status in HANDED_OFF_STATUSES:
            # Phase 1P.6: the customer is talking to (or waiting on) a human.
            # The follow-up is already validated, origin-checked, rate-limited,
            # deduplicated, and persisted above; send it straight into the
            # human conversation. No AgentWorkflowService.analyze, no RAG, no
            # tool, no IntegrationJob, no approval. The session status is
            # preserved and the widget is told whether a human is actively
            # assigned so it never downgrades human_assigned.
            log.info(
                "public_chat_handed_off_message_received",
                organization_id=session.organization_id,
                session_id=session.id,
                conversation_id=conversation.id,
                message_id=inbound.id,
                status=session.status,
            )
            return {
                "message_id": inbound.id,
                "reply": None,
                "status": session.status,
                "handoff": session.status == "human_requested",
                "processing_state": "handoff",
            }
        timer.mark("persist_inbound")

        if use_async:
            job_id = await cls._ensure_turn_job(
                db,
                session=session,
                inbound_id=inbound.id,
                client_message_id=client_message_id,
            )
            timer.mark("enqueue")
            timer.log("accept", organization_id=session.organization_id, session_id=session.id)
            return cls._accepted(session=session, inbound_id=inbound.id, job_id=job_id)

        result = await cls._ai_reply_turn(
            db,
            session=session,
            configuration=configuration,
            conversation=conversation,
            inbound=inbound,
            text=text,
            client_message_id=client_message_id,
            timer=timer,
        )
        timer.log("sync_turn", organization_id=result.pop("_organization_id"), session_id=result.pop("_session_id"))
        return result

    @staticmethod
    def _accepted(*, session: PublicChatSession, inbound_id: int, job_id: int) -> dict:
        # ``_turn_job_id``/``_organization_id`` are internal hand-offs to the
        # route (which dispatches the turn after this request's commit); the
        # route removes them before responding.
        return {
            "message_id": inbound_id,
            "reply": None,
            "status": session.status,
            "handoff": False,
            "processing_state": "accepted",
            "_turn_job_id": job_id,
            "_organization_id": session.organization_id,
        }

    @classmethod
    async def _ai_reply_turn(
        cls,
        db: AsyncSession,
        *,
        session: PublicChatSession,
        configuration: PublicChatConfiguration,
        conversation: Conversation,
        inbound: ConversationMessage,
        text: str,
        client_message_id: str,
        timer: "_StageTimer",
    ) -> dict:
        """The AI half of a chat turn, shared by the sync path and async jobs.

        Unchanged safety rules (handoff-only by default, the narrow grounded
        auto-reply carve-out, fail-closed RAG). Phase 1P.9 adds the tenant's
        monthly AI allowance check BEFORE any model call: an exhausted
        allowance hands the conversation to a human without calling a model.
        """
        organization_id = session.organization_id
        ticket_result = await db.execute(
            select(Ticket).where(
                Ticket.id == session.ticket_id,
                Ticket.organization_id == organization_id,
            )
        )
        ticket = ticket_result.scalar_one_or_none()
        if ticket is None:
            raise PublicChatSessionNotFoundError("Session ticket not found.")

        allowance = await TenantAIAllowanceService.check(
            db,
            organization_id=organization_id,
            configuration=configuration,
        )
        timer.mark("allowance")
        if not allowance.allowed:
            log.warning(
                "public_chat_ai_allowance_exhausted",
                organization_id=organization_id,
                session_id=session.id,
                reason=allowance.reason,
                turns_used=allowance.turns_used,
                turn_limit=allowance.turn_limit,
            )
            reply_text = await cls.handoff_reply_for(db, organization_id)
            if session.status == "ai_active":
                session = await PublicChatRepository.update_session_for_tenant(
                    db,
                    session=session,
                    changes={"status": "human_requested"},
                    organization_id=organization_id,
                )
            await cls._insert_reply_message(
                db,
                conversation=conversation,
                body=reply_text,
                client_message_id=client_message_id,
            )
            return {
                "message_id": inbound.id,
                "reply": reply_text,
                "status": session.status,
                "handoff": True,
                "processing_state": "handoff",
                "_organization_id": organization_id,
                "_session_id": session.id,
            }

        result = await agent_workflow_service.analyze(
            db=db,
            ticket_id=ticket.id,
            organization_id=organization_id,
            allow_auto_queue=True,
            persist_run=True,
            authz=None,
        )

        timer.mark("agent")

        # ---- bounded reply selection (Phase 1P.1 + 1P.5) ----
        # Default is handoff-only: the repo's tool policy forces
        # requires_human_approval on every customer-facing action
        # (respond/route/escalate), so those runs are escalated to staff and
        # the widget shows fixed text — never live model output. Only no-op
        # decisions complete the turn with the fallback.
        #
        # Phase 1P.5 adds one narrow, opt-in carve-out: a tenant that set
        # ``grounded_auto_reply_enabled`` may have a pure informational
        # ``respond`` turn answered from the knowledge base, but only when
        # ``public_answer_eligible`` accepts the answer. Every other outcome
        # (flag off, non-informational intent, a business tool, a non-grounded
        # or un-cited answer, or any RAG error) fails closed to the human
        # handoff.
        handoff = False
        reply_text = FALLBACK_REPLY
        run = await AgentRunRepository.get_by_run_id_for_tenant(
            db,
            run_id=result["run_id"],
            organization_id=organization_id,
        )
        run_action = run.action if run is not None else None

        grounded_reply: _GroundedAutoReply | None = None
        if cls._grounded_auto_reply_requested(
            configuration=configuration,
            result=result,
            run=run,
        ):
            try:
                grounded_reply = await cls._grounded_auto_reply_or_none(
                    db,
                    organization_id=organization_id,
                    question=text,
                )
            except Exception:
                # A retrieval/RAG failure must never surface as a 500: roll
                # the failed transaction back (which expires ORM state) and
                # reload the objects the handoff path still needs, then fail
                # closed to the human handoff.
                log.exception("public_chat_grounded_auto_reply_failed")
                await db.rollback()
                await db.refresh(inbound)
                await db.refresh(session)
                await db.refresh(conversation)
                await cls._record_rag_failure(
                    db,
                    organization_id=organization_id,
                )
                grounded_reply = None

        if grounded_reply is not None:
            reply_text = grounded_reply.text
        elif run_action is None or run_action not in SAFE_AUTOREPLY_ACTIONS:
            handoff = True
            reply_text = await cls.handoff_reply_for(db, organization_id)

        if handoff and session.status == "ai_active":
            session = await PublicChatRepository.update_session_for_tenant(
                db,
                session=session,
                changes={"status": "human_requested"},
                organization_id=session.organization_id,
            )

        timer.mark("rag")
        await cls._insert_reply_message(
            db,
            conversation=conversation,
            body=reply_text,
            client_message_id=client_message_id,
        )
        timer.mark("persist_reply")

        if grounded_reply is not None and run is not None:
            await cls._record_grounded_auto_reply(
                db,
                run=run,
                session=session,
                reply=grounded_reply,
            )

        # The identifiers are logged, never returned: the public response schema
        # is deliberately free of anything a caller could use to address another
        # tenant's session, but an operator still needs to find this exact
        # conversation when a pilot customer reports a bad reply.
        log.info(
            "public_chat_reply_sent",
            organization_id=session.organization_id,
            session_id=session.id,
            message_id=inbound.id,
            status=session.status,
            handoff=handoff,
        )

        return {
            "message_id": inbound.id,
            "reply": reply_text,
            "status": session.status,
            "handoff": handoff,
            "processing_state": "handoff" if handoff else "completed",
            "_organization_id": session.organization_id,
            "_session_id": session.id,
        }


