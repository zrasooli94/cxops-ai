"use strict";

const assert = require("node:assert/strict");
const { describe, it } = require("node:test");
const { readFileSync } = require("node:fs");
const path = require("node:path");

const core = require("./review-core.js");

function sampleRows() {
  const a = Object.fromEntries(core.FIELDS.map((key) => [key, ""]));
  Object.assign(a, {
    dataset_id: core.EXPECTED_DATASET,
    review_key: "aster-direct-contradiction:c1",
    fingerprint: "a".repeat(64),
    tenant_id: "aster-synthetic",
    case_id: "aster-direct-contradiction",
    claim_id: "c1",
    claim_text: "All Aster bicycle repairs are free.",
    answer_text: "All Aster bicycle repairs are free. [S1]",
    cited_source_ids: "S1",
    cited_source_passages: "[S1] REV aster-v1\nAster bicycle repairs are not free.",
  });
  const b = {
    ...a,
    fingerprint: "b".repeat(64),
    review_key: "birch-farsi:c1",
    tenant_id: "birch-synthetic",
    case_id: "birch-farsi",
    claim_text: "این خدمات رایگان نیست.",
    answer_text: "این خدمات رایگان نیست. [S1]",
    cited_source_passages: '[S1] REV birch-v1\nاین خدمات "رایگان" نیست.\n\nافزوده',
  };
  return [a, b];
}

function sheet(rows = sampleRows()) {
  return core.serializeCsv([
    [...core.FIELDS],
    ...rows.map((row) => core.FIELDS.map((field) => row[field])),
  ]);
}

describe("lossless C6 CSV transport", () => {
  it("parses UTF-8, Persian, multiline source passages and double quotes", () => {
    const src = sheet();
    const imported = core.validateWorksheet("\ufeff" + src, 1, "reviewer-human-A");
    assert.equal(imported.length, 2);
    assert.equal(imported[1].claim_text, "این خدمات رایگان نیست.");
    assert.match(imported[1].cited_source_passages, /"رایگان"/);
    assert.match(imported[1].cited_source_passages, /\n\nافزوده/);
    assert.deepEqual(
      core.parseCsv(src),
      core.parseCsv(core.exportReviewerCsv(imported, 1, "reviewer-human-A")),
    );
  });

  it("rejects invalid CSV quoting, unquoted quotes, stray postquote content", () => {
    for (const s of ['a,"unterminated', 'a,a"b,c', '"a"x,b']) {
      assert.throws(() => core.parseCsv(s), /CSV/);
    }
  });

  it("rejects unexpected column counts and a duplicated or unknown header", () => {
    assert.throws(() => core.validateWorksheet(
      sheet().replace("reviewer_1", "reviewer_2"), 1, "A1",
    ), /columns/);
    assert.throws(() => core.validateWorksheet(
      core.serializeCsv([[...core.FIELDS], ["a"]]), 1, "A1",
    ), /columns/);
  });

  it("refuses extra rows, duplicate claim keys, unapproved tenant and source", () => {
    assert.throws(() => core.validateWorksheet(
      sheet([...sampleRows(), sampleRows()[0]]), 1, "A1",
    ), /synthetic worksheet/);
    const fakeTenant = sampleRows();
    fakeTenant[0].tenant_id = "real-customer";
    assert.throws(() => core.validateWorksheet(
      sheet(fakeTenant), 1, "A1",
    ), /synthetic worksheet/);
    const missingSource = sampleRows();
    missingSource[0].cited_source_ids = "S999";
    assert.throws(() => core.validateWorksheet(
      sheet(missingSource), 1, "A1",
    ), /cited source/);
  });

  it("rejects other-reviewer or adjudicator columns even if apparently complete", () => {
    for (const field of ["reviewer_2", "reviewer_2_label", "adjudicator"]) {
      const rows = sampleRows();
      rows[0][field] = "someone";
      assert.throws(
        () => core.validateWorksheet(sheet(rows), 1, "A1"), /another reviewer/,
      );
    }
  });

  it("requires a consistent author when resuming a private reviewer draft", () => {
    const rows = sampleRows();
    rows[0].reviewer_1 = "A1";
    const imported = core.validateWorksheet(sheet(rows), 1, "A1");
    assert.equal(imported[0].reviewer_1, "A1");
    assert.throws(
      () => core.validateWorksheet(sheet(rows), 1, "B2"),
      /Review ID does not match/,
    );
  });

  it("does not substitute fake identity data for blank reviewer fields", () => {
    const imported = core.validateWorksheet(sheet(), 1, "real-reviewer-id");
    assert.equal(imported[0].reviewer_1, "");
    assert.equal(imported[0].reviewer_1_label, "");
    assert.equal(imported[0].reviewer_2, "");
    assert.equal(core.progress(imported, 1, "real-reviewer-id").finished, 0);
  });

  it("imports the EXACT CSV generated by C6 Python when supplied to CI", () => {
    const filename = process.env.C7_BLANK_SHEET;
    if (!filename) return;
    const rows = core.validateWorksheet(readFileSync(filename, "utf8"), 1, "A1");
    assert.equal(rows.length, 12);
    assert.deepEqual(rows.map((r) => r.claim_id).filter(Boolean).length, 12);
    assert.ok(rows.every((r) => r.reviewer_1_label === ""));
  });
});

describe("reviewer slot, validity and evidence", () => {
  it("keeps reviewer A isolated from reviewer B", () => {
    const src = core.validateWorksheet(sheet(), 1, "A1");
    const after = core.editRow(src, 0, 1, "A1", {
      label: "contradicted",
      evidence: "Aster bicycle repairs are not free.",
      note: "",
    });
    assert.equal(src[0].reviewer_1_label, "");
    assert.equal(after[0].reviewer_1_label, "contradicted");
    assert.equal(after[0].reviewer_2_label, "");
    assert.equal(core.reviewStatus(after[0], 1, "A1").complete, true);
    assert.throws(
      () => core.editRow(after, 0, 1, "A1", { reviewer_2: "evil" }),
      /Only your own/,
    );
    assert.deepEqual(core.progress(after, 1, "A1"), {
      finished: 1, total: 2, complete: false,
    });
  });

  it("requires direct evidence for supported and contradicted, not citation headers", () => {
    const rows = core.validateWorksheet(sheet(), 1, "A1");
    for (const evidence of ["", "S1", "aster-v1", "made-up passage"]) {
      const edited = core.editRow(rows, 0, 1, "A1", {
        label: "contradicted", evidence,
      });
      assert.equal(core.reviewStatus(edited[0], 1, "A1").complete, false);
    }
    const valid = core.editRow(rows, 0, 1, "A1", {
      label: "contradicted",
      evidence: "Aster bicycle repairs are not free.",
    });
    assert.equal(core.reviewStatus(valid[0], 1, "A1").complete, true);
  });

  it("requires meaningful rationale for unsupported or unclear labels", () => {
    const rows = core.validateWorksheet(sheet(), 1, "A1");
    for (const label of ["unsupported", "unclear"]) {
      const invalid = core.editRow(rows, 0, 1, "A1", {
        label, note: "No.",
      });
      assert.equal(core.reviewStatus(invalid[0], 1, "A1").complete, false);
      const valid = core.editRow(rows, 0, 1, "A1", {
        label, note: "No cited passage establishes that price.",
      });
      assert.equal(core.reviewStatus(valid[0], 1, "A1").complete, true);
    }
  });

  it("never treats an incomplete draft as a completed review", () => {
    const rows = core.validateWorksheet(sheet(), 1, "A1");
    assert.equal(core.progress(rows, 1, "A1").complete, false);
    const partial = core.editRow(rows, 0, 1, "A1", {
      label: "contradicted", evidence: "Aster bicycle repairs are not free.",
    });
    assert.equal(core.progress(partial, 1, "A1").complete, false);
    const restored = core.validateWorksheet(
      core.exportReviewerCsv(partial, 1, "A1"), 1, "A1",
    );
    assert.deepEqual(restored, partial);
  });

  it("blocks exporting a selected label without required evidence", () => {
    const rows = core.validateWorksheet(sheet(), 1, "A1");
    const incomplete = core.editRow(rows, 0, 1, "A1", { label: "supported" });
    assert.throws(
      () => core.exportReviewerCsv(incomplete, 1, "A1"),
      /Finish or clear/,
    );
  });

  it("preserves a draft-in-progress but will not label it complete", () => {
    const rows = core.validateWorksheet(sheet(), 1, "A1");
    const partial = core.editRow(rows, 0, 1, "A1", {
      label: "supported", evidence: "insufficient quote",
    });
    assert.equal(core.progress(partial, 1, "A1").complete, false);
    assert.throws(
      () => core.exportReviewerCsv(partial, 1, "A1"), /Finish or clear/,
    );
    const draft = core.exportReviewerCsv(
      partial, 1, "A1", { allowIncomplete: true },
    );
    const imported = core.validateWorksheet(draft, 1, "A1");
    assert.equal(imported[0].reviewer_1_label, "supported");
    assert.equal(imported[0].reviewer_1_evidence, "insufficient quote");
    assert.equal(core.progress(imported, 1, "A1").complete, false);
  });

  it("refuses formula-leading source values, including malformed protected CSV", () => {
    const rows = sampleRows();
    rows[0].answer_text = "=HYPERLINK('bad') [S1]";
    assert.throws(
      () => core.validateWorksheet(sheet(rows), 1, "A1"),
      /spreadsheet-unsafe/,
    );
  });

  it("refuses spreadsheet-formula payloads from reviewer-entered fields", () => {
    for (const value of ["=HYPERLINK('bad')", " +SUM(1,2)", "@foo"]) {
      assert.equal(core.safeIdentity(value), false);
      const rows = core.validateWorksheet(sheet(), 1, "A1");
      assert.throws(
        () => core.editRow(rows, 0, 1, "A1", { note: value }),
        /formula-like/,
      );
    }
  });

  it("rejects unsupported reviewer slots and excessively long text", () => {
    assert.throws(
      () => core.validateWorksheet(sheet(), 3, "A1"), /Choose Reviewer/,
    );
    assert.throws(
      () => core.editRow(sampleRows(), 0, 1, "A1", { note: "a".repeat(501) }),
      /Invalid/,
    );
    assert.throws(
      () => core.editRow(sampleRows(), 0, 1, "A1", { label: "suspicious" }),
      /Invalid|label/,
    );
  });
});

describe("UI remains offline and renders evidence as plain text", () => {
  const html = readFileSync(path.join(__dirname, "index.html"), "utf8");
  const app = readFileSync(path.join(__dirname, "app.js"), "utf8");

  it("has local-only scripts/styles and forbids network connections in CSP", () => {
    assert.match(html, /connect-src 'none'/);
    assert.match(html, /src="\.\/review-core\.js"/);
    assert.match(html, /src="\.\/app\.js"/);
    assert.match(html, /href="\.\/review\.css"/);
    assert.doesNotMatch(html, /https?:\/\//i);
    assert.doesNotMatch(html, /<iframe|<form|onload=|onclick=/i);
  });

  it("does not upload, execute, store, or inject untrusted CSV contents", () => {
    assert.doesNotMatch(
      app,
      /\bfetch\(|XMLHttpRequest|WebSocket|sendBeacon|localStorage|indexedDB|innerHTML|eval\(/,
    );
    assert.match(app, /ui\.claim\.textContent = row\.claim_text/);
    assert.match(app, /ui\.source\.textContent = row\.cited_source_passages/);
    assert.match(app, /ui\.answer\.textContent = row\.answer_text/);
    assert.match(app, /core\.validateWorksheet\(/);
    assert.match(app, /core\.exportReviewerCsv\(/);
    assert.match(app, /Blob\(/);
    assert.match(app, /URL\.revokeObjectURL/);
  });
});
